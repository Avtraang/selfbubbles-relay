@dataclass
class DemoInfo:
    """What :func:`build_demo_db` produced."""

    path: Path
    files_dir: Path
    attachment_path: Path
    state_path: Path
    seed: int
    now: float                                  # Unix seconds the newest scene is anchored to
    chat_rowids: dict[str, int] = field(default_factory=dict)
    message_rowids: dict[str, list[int]] = field(default_factory=dict)   # chat guid -> ROWIDs
    message_count: int = 0
    reply_count: int = 0
    tapback_count: int = 0
    attachment_count: int = 0
    link_count: int = 0
    edited_count: int = 0

    @property
    def chat_count(self) -> int:
        return len(self.chat_rowids)


def _parse_now(value: str | None) -> float:
    if value is None:
        return time.time()
    try:
        parsed = dt.datetime.fromisoformat(value)
    except ValueError as e:
        raise SystemExit(f"--now must be an ISO 8601 timestamp, e.g. 2026-10-06T18:00:00: {e}") from None
    if parsed.tzinfo is None:
        parsed = parsed.astimezone()             # naive -> local time
    return parsed.timestamp()


def _stored_path(path: Path) -> str:
    """What goes into ``attachment.filename`` for the file at ``path``:
    ``~/...`` when it is under the home directory (the form real chat.db rows
    use, and the relay expands it), so the database does not carry the account
    name; the absolute path otherwise."""
    try:
        return "~/" + path.relative_to(Path.home().resolve()).as_posix()
    except ValueError:
        return str(path)


def _schedule(now: float, rng: random.Random) -> list[tuple[float, Scene, Turn]]:
    """Every turn with its Unix timestamp, in chronological order.

    Scenes start at their local wall-clock time ``days_ago`` days before ``now``
    (computed on naive local datetimes, so each date gets its own UTC offset);
    inside a scene each turn follows the previous one by its ``gap`` minutes
    plus 0-90 seconds of jitter.  A scene anchored to "now" (``hour=None``) is
    shifted so its last message is :data:`ANCHOR_MINUTES_BEFORE_NOW` minutes
    old; any other scene that would reach past ``now`` is shifted back to end
    ten minutes before it.
    """
    today = dt.datetime.fromtimestamp(now)               # naive local time, on purpose
    out: list[tuple[float, Scene, Turn]] = []
    for scene in SCRIPT:
        if scene.hour is None:
            t = 0.0                                      # placeholder: shifted below
        else:
            day = today - dt.timedelta(days=scene.days_ago)
            t = day.replace(hour=scene.hour, minute=scene.minute or 0, second=rng.randrange(60),
                            microsecond=0).timestamp()
        stamps = [t]
        for turn in scene.turns[1:]:
            t += turn.gap * 60 + rng.randrange(0, 91)
            stamps.append(t)
        if scene.hour is None:
            shift = (now - ANCHOR_MINUTES_BEFORE_NOW * 60) - stamps[-1]
        else:
            shift = min(0.0, (now - 10 * 60) - stamps[-1])
        stamps = [s + shift for s in stamps]
        out.extend(zip(stamps, [scene] * len(stamps), scene.turns))
    out.sort(key=lambda item: item[0])
    return out


def build_demo_db(output: Path, *, seed: int = 1, now: float | None = None) -> DemoInfo:
    """Create ``output`` (any path not under ``~/Library``) and fill it.

    ``output`` may not be inside the relay checkout either, and an existing
    output is replaced only when :func:`is_demo_database` says this script made
    it.  ``now`` is Unix seconds (default: the current time).  The same
    ``seed``, ``now``, output path and local time zone give the same rows: scene
    times are local wall-clock times, and the attachment row stores where the
    PNG is.  Attachment files go to ``<stem>_files/`` beside the database.
    """
    path = check_output_path(Path(output))
    path.parent.mkdir(parents=True, exist_ok=True)
    _remove_previous(path)
    now = time.time() if now is None else float(now)
    rng = random.Random(seed)

    files_dir = path.with_name(path.stem + "_files")
    files_dir.mkdir(exist_ok=True)
    photo = make_png(320, 240, seed)
    attachment_path = files_dir / ATTACHMENT_NAME
    attachment_path.write_bytes(photo)
    hero = make_png(64, 40, seed + 1, compress=0)       # > 3000 bytes: embedded hero image

    info = DemoInfo(path=path, files_dir=files_dir, attachment_path=attachment_path,
                    state_path=path.with_name(path.stem + "_relay_state.json"),
                    seed=seed, now=now)
    fx = create_fixture_db(path, SCHEMA_PROFILE)
    w = fx.writer
    try:
        w.execute(f"CREATE TABLE {MARKER_TABLE} (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
        w.executemany(f"INSERT INTO {MARKER_TABLE} (key, value) VALUES (?, ?)", [
            ("generator", "selfbubbles-relay tools/make_demo_db.py"),
            ("schema_profile", SCHEMA_PROFILE),
            ("seed", str(seed)),
            ("now_unix", repr(now)),
            ("fictional", "every person, number, address, text and image in this file is invented"),
        ])

        handles = {addr: builders.add_handle(w, addr, service=svc) for addr, (_, svc) in PEOPLE.items()}
        for spec in CHATS.values():
            rowid = builders.add_chat(
                w, spec.guid, 43 if spec.is_group else 45,
                identifier=spec.guid.split(";")[-1],
                display_name=spec.display_name, service_name=spec.service,
                handles=[handles[m] for m in spec.members],
            )
            info.chat_rowids[spec.guid] = rowid
            info.message_rowids[spec.guid] = []

        guids_by_label: dict[tuple[str, int], str] = {}
        n = 0
        for stamp, scene, turn in _schedule(now, rng):
            n += 1
            guid = f"DEMO-MSG-{n:04d}"
            spec = CHATS[scene.chat_guid]
            chat_rowid = info.chat_rowids[scene.chat_guid]
            date_ns = unix_to_apple(stamp)
            from_me = turn.sender == "me"
            handle = None if from_me else handles[turn.sender]
            key = (scene.chat_guid, scene.days_ago)
            # Incoming rows were read 45 s later; outgoing iMessages got a read
            # receipt then (SMS has none); outgoing rows were delivered after 2 s.
            read_at = date_ns + 45_000_000_000
            common = dict(date_ns=date_ns, is_from_me=int(from_me), handle=handle,
                          service=spec.service, guid=guid,
                          date_delivered=date_ns + 2_000_000_000 if from_me else 0,
                          date_read=0 if (from_me and spec.service == "SMS") else read_at)
            if turn.kind == "tapback":
                target = guids_by_label[(key, turn.ref)]
                verb_index = int(turn.text)
                rowid = builders.add_message(
                    w, chat_rowid, text=_tapback_text(scene, verb_index, turn.ref),
                    assoc_guid=f"p:0/{target}", assoc_type=2000 + verb_index, **common)
                info.tapback_count += 1
            elif turn.kind == "photo":
                rowid = builders.add_message(w, chat_rowid, text=None, has_att=1, **common)
                builders.add_attachment(
                    w, rowid, ATTACHMENT_GUID, "image/png", ATTACHMENT_NAME,
                    _stored_path(attachment_path),
                    uti="public.png", total_bytes=len(photo), created_date=date_ns)
                info.attachment_count += 1
            elif turn.kind in ("apple_news", "link"):
                if turn.kind == "apple_news":
                    archive = build_link_archive(
                        turn.text, "Council approves protected bike lanes on Harbor Street",
                        "After four years of hearings, the city will build 3.2 miles of separated "
                        "lanes between the harbor and the rail station.",
                        "Harbor Gazette", wrapped=True)
                    archive["$objects"].append(hero)        # the embedded hero image, a real PNG
                else:
                    archive = build_link_archive(
                        turn.text, "Ridgeline Loop Trail", "9.4 mi loop, 2,100 ft elevation gain. "
                        "Parking fills by 8 am on weekends.", "example.com", wrapped=True)
                payload = dump_archive(archive)
                rowid = builders.add_message(
                    w, chat_rowid, text=turn.text, body=encode_attributed_body(turn.text),
                    balloon=LINK_BALLOON, payload=payload, **common)
                info.link_count += 1
            else:
                reply_to = guids_by_label[(key, turn.ref)] if turn.ref else None
                rowid = builders.add_message(
                    w, chat_rowid, text=turn.text, body=encode_attributed_body(turn.text),
                    reply_to=reply_to, reply_to_part="0:0:0" if reply_to else None,
                    date_edited=date_ns + 90_000_000_000 if turn.edited else 0, **common)
                if reply_to:
                    info.reply_count += 1
                if turn.edited:
                    info.edited_count += 1
            if turn.label:
                guids_by_label[(key, turn.label)] = guid
            info.message_rowids[scene.chat_guid].append(rowid)
            info.message_count += 1
        w.execute("PRAGMA wal_checkpoint(TRUNCATE)").fetchall()
    finally:
        w.close()
    return info


def _tapback_text(scene: Scene, verb_index: int, label: str | None) -> str:
    """An approximation of the text Messages stores for a tapback: the verb plus
    the quoted target text, or "an image" for a photo.  The relay does not rely
    on it (its thread previews say "<verb> a message")."""
    for t in scene.turns:
        if t.label == label:
            verb = TAPBACK_VERBS[verb_index]
            return f"{verb} an image" if t.kind == "photo" else f"{verb} \u201c{t.text}\u201d"
    raise KeyError(label)


