class UnsafeOutputPath(RuntimeError):
    """The output path is somewhere a real Messages database could live, or
    inside the relay checkout."""


class NotADemoDatabase(RuntimeError):
    """The output path exists and was not made by this script."""


def check_output_path(path: Path) -> Path:
    """``path`` resolved, or :class:`UnsafeOutputPath` when it is under
    ``~/Library`` or inside the relay checkout.

    Purely lexical; nothing is opened or created.
    """
    resolved = Path(path).expanduser().resolve()
    library = (Path.home() / "Library").resolve()
    if resolved == library or resolved.is_relative_to(library):
        raise UnsafeOutputPath(f"refusing to write under ~/Library (where the real chat.db lives): {resolved}")
    if resolved == ROOT or resolved.is_relative_to(ROOT):
        raise UnsafeOutputPath(
            f"refusing to write inside the relay checkout ({ROOT}): its .gitignore does not "
            "cover a demo database, and the state file beside the database records the push token "
            "of any phone that connects. Choose a path outside it, e.g. ~/selfbubbles-demo/chat.db")
    return resolved


def is_demo_database(path: Path) -> bool:
    """True when ``path`` is a SQLite file carrying the :data:`MARKER_TABLE`."""
    try:
        # percent-encoded: a "#", "?" or "%" in the path is not URI syntax
        conn = sqlite3.connect(f"file:{quote(str(path))}?mode=ro", uri=True)
    except sqlite3.Error:
        return False
    try:
        row = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (MARKER_TABLE,)
        ).fetchone()
        return row is not None
    except sqlite3.Error:
        return False
    finally:
        conn.close()


def _remove_previous(path: Path) -> None:
    if path.exists():
        if not is_demo_database(path):
            raise NotADemoDatabase(
                f"{path} exists and is not a database made by this script; delete it yourself first")
        path.unlink()
    for suffix in ("-wal", "-shm"):
        side = path.with_name(path.name + suffix)
        if side.exists():
            side.unlink()


