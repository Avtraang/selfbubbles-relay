def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="make_demo_db.py",
        description="Build a fictional chat.db for SelfBubbles screenshots and demos, "
                    "or serve its fictional contact names to a demo relay.")
    parser.add_argument("output", type=Path, nargs="?",
                        help="where to write the database: any path that is not under ~/Library "
                             "and not inside the relay checkout, e.g. ~/selfbubbles-demo/chat.db")
    parser.add_argument("--seed", type=int, default=1, help="jitter seed for timestamps and colours (default 1)")
    parser.add_argument("--now", default=None, metavar="ISO8601",
                        help="anchor the newest messages here instead of the current time "
                             "(e.g. 2026-10-06T18:00:00; the same seed, now, output path and "
                             "time zone give the same rows)")
    parser.add_argument("--relay-port", type=int, default=DEMO_RELAY_PORT, metavar="N",
                        help=f"the demo relay's port in the printed recipe (default {DEMO_RELAY_PORT})")
    parser.add_argument("--contacts-port", type=int, default=DEMO_CONTACTS_PORT, metavar="N",
                        help="the names server's port in the printed recipe "
                             f"(default {DEMO_CONTACTS_PORT})")
    parser.add_argument("--serve-contacts", nargs="?", type=int, const=DEMO_CONTACTS_PORT,
                        default=None, metavar="PORT",
                        help="instead of building: serve the fictional names on 127.0.0.1:PORT "
                             f"(default {DEMO_CONTACTS_PORT}) for a demo relay, until Ctrl-C")
    args = parser.parse_args(argv)
    if args.serve_contacts is not None:
        if args.output is not None:
            parser.error("--serve-contacts runs on its own; build the database in a separate run")
        return serve_contacts(args.serve_contacts)
    if args.output is None:
        parser.error("give the path of the database to build, or --serve-contacts")
    try:
        info = build_demo_db(args.output, seed=args.seed, now=_parse_now(args.now))
    except (UnsafeOutputPath, NotADemoDatabase) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    ports = (args.relay_port, args.contacts_port)
    print(run_instructions(info, relay_port=args.relay_port, contacts_port=args.contacts_port,
                           busy_ports=tuple(p for p in ports if port_in_use(p))))
    return 0


