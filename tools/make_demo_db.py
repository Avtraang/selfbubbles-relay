def make_png(width: int, height: int, seed: int = 0, *, compress: int = 6) -> bytes:
    """A real 8-bit RGB PNG: a two-tone gradient with a seeded diagonal stripe.

    ``compress=0`` stores the rows uncompressed, which is how the link hero
    image is kept above the library's 3000-byte embedded-image threshold.
    """
    rng = random.Random(seed)
    a = (rng.randrange(60, 200), rng.randrange(60, 200), rng.randrange(120, 255))
    b = (rng.randrange(180, 255), rng.randrange(90, 200), rng.randrange(40, 160))
    stripe = rng.randrange(width // 4, (3 * width) // 4)
    rows = bytearray()
    for y in range(height):
        rows.append(0)                                   # filter type: none
        fy = y / max(1, height - 1)
        for x in range(width):
            fx = x / max(1, width - 1)
            t = (fx + fy) / 2
            px = [int(a[i] + (b[i] - a[i]) * t) for i in range(3)]
            if abs((x - stripe) - (y - height // 2)) < 3:
                px = [255 - c for c in px]
            rows.extend(px)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(bytes(rows), compress)) + chunk(b"IEND", b""))


