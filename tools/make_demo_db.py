#: The printed command, one tuple per line.  Every key of :func:`relay_env`
#: appears exactly once.
_RECIPE_LAYOUT: tuple[tuple[str, ...], ...] = (
    ("IMSG_CHATDB",),
    ("IMSG_STATE",),
    ("IMSG_PORT", "IMSG_TOKEN"),
    ("IMSG_SELF", "TEXT_RELAY_LABEL", "APPLE_NEWS_PREVIEWS"),
    ("BB_URL", "BB_PASSWORD"),
    ("BEEPER_TOKEN", "FCM_CREDS", "HA_TOKEN", "MAPKIT_TOKEN"),
    ("SEND_ENGINES", "SEND_APPLESCRIPT_FALLBACK", "IMESSAGE_CLI"),
    ("FEATURE_FACETIME", "FEATURE_MAP", "FEATURE_TRANSLATE", "FEATURE_VOICE"),
)


def relay_env(info: DemoInfo, token: str, *, relay_port: int = DEMO_RELAY_PORT,
              contacts_port: int = DEMO_CONTACTS_PORT) -> dict[str, str]:
    """Every variable the recipe sets for the demo relay.

    The empty values are deliberate.  The relay loads a ``.env`` beside
    ``relay.py`` without overriding, so a variable that is set here, even to
    nothing, is not taken from it; see "Running a demo relay" in the module
    docstring for what each one keeps out.
    """
    return {
        "IMSG_CHATDB": str(info.path),
        "IMSG_STATE": str(info.state_path),
        "IMSG_PORT": str(relay_port),
        "IMSG_TOKEN": token,
        "IMSG_SELF": SELF_NUMBER,
        "TEXT_RELAY_LABEL": DEMO_PHONE_LABEL,
        "APPLE_NEWS_PREVIEWS": "0",
        "BB_URL": f"http://127.0.0.1:{contacts_port}",
        "BB_PASSWORD": DEMO_CONTACTS_PASSWORD,
        "BEEPER_TOKEN": "",
        "FCM_CREDS": "",
        "HA_TOKEN": "",
        "MAPKIT_TOKEN": "",
        "SEND_ENGINES": "",
        "SEND_APPLESCRIPT_FALLBACK": "0",
        "IMESSAGE_CLI": "0",
        "FEATURE_FACETIME": "0",
        "FEATURE_MAP": "0",
        "FEATURE_TRANSLATE": "0",
        "FEATURE_VOICE": "0",
    }


def relay_command(env: dict[str, str]) -> list[str]:
    """The shell command that starts the demo relay with ``env``, as lines
    joined by a trailing backslash.  Values are shell-quoted, so a path with a
    space or a ``#`` survives the paste; an empty value prints as ``KEY=``."""
    laid_out = [key for line in _RECIPE_LAYOUT for key in line]
    if sorted(laid_out) != sorted(env):
        raise KeyError(f"recipe layout and environment differ: {sorted(set(laid_out) ^ set(env))}")
    lines = [" ".join(f"{key}={shlex.quote(env[key]) if env[key] else ''}" for key in line) + " \\"
             for line in _RECIPE_LAYOUT]
    return lines + ["venv/bin/python relay.py"]


def _busy_notes(busy_ports: tuple[int, ...], relay_port: int, contacts_port: int) -> list[str]:
    notes = []
    if relay_port in busy_ports:
        notes += [
            f"NOTE: something already listens on port {relay_port} on this Mac. If it is a demo relay",
            "you left running, stop it before step 2. Otherwise build again with --relay-port N",
            "(a free port): depending on how the other program listens, the relay either fails",
            "to start or starts beside it, and step 3 then reaches the other program.",
            "",
        ]
    if contacts_port in busy_ports:
        notes += [
            f"NOTE: something already listens on port {contacts_port} on this Mac. If it is the names server",
            "of step 1, leave it running and skip step 1. Otherwise build again with",
            "--contacts-port N.",
            "",
        ]
    return notes


