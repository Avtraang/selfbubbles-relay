def contacts_payload() -> list[dict]:
    """:data:`PEOPLE` as BlueBubbles contact records: the fields the relay's
    ``load_contacts`` reads (``displayName``, ``phoneNumbers`` / ``emails``
    with an ``address`` each)."""
    out = []
    for handle, (name, _service) in PEOPLE.items():
        first, _, last = name.partition(" ")
        record: dict = {"displayName": name, "firstName": first, "lastName": last,
                        "phoneNumbers": [], "emails": []}
        record["emails" if "@" in handle else "phoneNumbers"].append({"address": handle})
        out.append(record)
    return out


class _ContactsHandler(BaseHTTPRequestHandler):
    """Two reads and nothing else.  A 2xx answer to a write would read to the
    relay as "BlueBubbles sent it", so every write is a 501."""

    server_version = "selfbubbles-demo-contacts"
    sys_version = ""

    def _json(self, status: int, body: dict) -> None:
        data = json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self) -> None:  # noqa: N802  (http.server's naming)
        path = urlsplit(self.path).path.rstrip("/")
        if path == "/api/v1/ping":
            self._json(200, {"status": 200, "message": "demo contacts server", "data": "pong"})
        elif path == "/api/v1/contact":
            self._json(200, {"status": 200, "message": "demo contacts server",
                             "data": contacts_payload()})
        else:
            self._json(404, {"status": 404, "message": "demo contacts server: only the ping "
                                                       "and the contact list are served"})

    def _refuse(self) -> None:
        try:                                             # drain the body before answering
            self.rfile.read(int(self.headers.get("Content-Length") or 0))
        except (ValueError, OSError):
            pass
        self._json(501, {"status": 501, "message": "demo contacts server: read-only, "
                                                   "nothing is sent"})

    do_POST = do_PUT = do_PATCH = do_DELETE = _refuse  # noqa: N815

    def log_message(self, format: str, *args) -> None:  # noqa: A002
        """Silent: the default writes the request line, and the relay puts its
        BlueBubbles password in the query string."""


def port_in_use(port: int) -> bool:
    """True when something on this Mac accepts TCP connections on
    ``127.0.0.1:port`` (a listener on every interface answers there too)."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.settimeout(0.5)
        return probe.connect_ex(("127.0.0.1", port)) == 0


def make_contacts_server(port: int = DEMO_CONTACTS_PORT) -> ThreadingHTTPServer:
    """The names server bound to ``127.0.0.1:port`` (``0`` picks a free port),
    not yet serving: call ``serve_forever()`` on it."""
    server = ThreadingHTTPServer(("127.0.0.1", port), _ContactsHandler)
    server.daemon_threads = True
    return server


def serve_contacts(port: int = DEMO_CONTACTS_PORT) -> int:
    """Serve the fictional names until interrupted (the ``--serve-contacts`` mode)."""
    # Checked by hand: http.server opens its socket with SO_REUSEADDR, which on
    # macOS lets a 127.0.0.1 bind succeed beside a listener on every interface.
    if port and port_in_use(port):
        print(f"error: something already listens on port {port} on this Mac (a names server you "
              f"left running?). Otherwise choose another port: --serve-contacts N here, and "
              f"build with --contacts-port N so the recipe matches.", file=sys.stderr)
        return 2
    try:
        server = make_contacts_server(port)
    except OSError as e:
        print(f"error: cannot listen on 127.0.0.1:{port}: {e}", file=sys.stderr)
        return 2
    bound = server.server_address[1]
    print(f"Serving {len(PEOPLE)} fictional contacts on http://127.0.0.1:{bound} "
          "(the ping and the contact list only; every write is refused with 501).")
    print("The demo relay asks for them when it starts, so start it after this. Ctrl-C stops.",
          flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print()
    finally:
        server.server_close()
    return 0


